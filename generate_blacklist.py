def norm(text):
    if not text:
        return ""
    return unicodedata.normalize('NFC', text.strip().lower())

def add_noun(words_set, word, gender='m'):
    w = norm(word)
    if not w:
        return
    words_set.add(w)
    if w.endswith('ा'):
        stem = w[:-1]
        if gender == 'm':
            words_set.add(stem + 'े')
            words_set.add(stem + 'ों')
        else:  # feminine noun ending in 'ा' (e.g. माता, लता, दिशा)
            words_set.add(stem + 'ाएं')
            words_set.add(stem + 'ाओं')
    elif w.endswith('ी'):
        stem = w[:-1]
        if gender == 'f':
            words_set.add(stem + 'ियाँ')
            words_set.add(stem + 'ियां')
            words_set.add(stem + 'ियों')
        else:  # masculine noun ending in 'ी' (e.g. हाथी, माली, धोबी)
            words_set.add(stem + 'ियों')
    elif w.endswith('ू'):
        stem = w[:-1]
        if gender == 'f':
            words_set.add(stem + 'ुएं')
            words_set.add(stem + 'ुओं')
        else:
            words_set.add(stem + 'ुओं')
    else:  # consonant ending
        if gender == 'm':
            words_set.add(w + 'ों')
        else:  # feminine ending in consonant (e.g. रात, बात, किताब)
            words_set.add(w + 'ें')
            words_set.add(w + 'ों')

